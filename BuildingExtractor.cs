using System.Collections.Specialized;
using MessagePack;

namespace Chaiser
{
    /// <summary>
    /// Resolves a single FactoryUnitConfigAsset (by AssetMap name) all the way down to a real
    /// Mesh + decoded base color texture, following the exact chain validated interactively:
    /// AssetMap -> direct-offset VFS decompress -> type tree -> best LOD -> mesh/material PPtr
    /// resolution (same CAB or via CABMap for externals) -> streamed vertex/texture data.
    /// </summary>
    public class BuildingExtractor
    {
        private readonly AssetResolver _resolver;
        private readonly string _assetMapPath;
        private AssetMap _assetMap;

        public BuildingExtractor(string assetMapPath, string cabMapPath, string vfsRoot)
        {
            _assetMapPath = assetMapPath;
            _resolver = new AssetResolver(cabMapPath, vfsRoot);
        }

        private AssetMap LoadAssetMap()
        {
            if (_assetMap != null) return _assetMap;
            using var stream = File.OpenRead(_assetMapPath);
            _assetMap = MessagePackSerializer.Deserialize<AssetMap>(stream, MessagePackSerializerOptions.Standard.WithCompression(MessagePackCompression.Lz4BlockArray));
            return _assetMap;
        }

        public List<AssetEntry> ListBuildingEntries()
        {
            return LoadAssetMap().AssetEntries
                .Where(e => e.Type == ClassIDType.MonoBehaviour
                         && e.Container != null
                         && e.Container.Contains("ciautogenerated/pc/building/", StringComparison.OrdinalIgnoreCase))
                .ToList();
        }

        /// <summary>
        /// Resolves one FactoryUnitConfigAsset by exact AssetMap name to a GltfPart (mesh +
        /// decoded base color texture from its highest-detail LOD). Returns null if the name
        /// isn't found or has no usable renderer data - callers decide whether that's fatal.
        /// </summary>
        public GltfPart ResolvePart(string assetName)
        {
            var entry = LoadAssetMap().AssetEntries.FirstOrDefault(e => e.Name == assetName && e.Type == ClassIDType.MonoBehaviour);
            if (entry == null)
            {
                return null;
            }

            using var seedReader = new FileReader(entry.Source);
            seedReader.Position = entry.Offset;
            var seedVfs = new VFSFile(seedReader, entry.Source);

            SerializedFile sf = null;
            FileReader cabReader = null;
            foreach (var node in seedVfs.Nodes)
            {
                var extracted = seedVfs.ExtractNode(node);
                var candidateReader = new FileReader(node.path, extracted, leaveOpen: true);
                if (candidateReader.FileType == FileType.AssetsFile)
                {
                    var candidateSf = new SerializedFile(candidateReader);
                    if (candidateSf.ObjectsByPathId.ContainsKey(entry.PathID))
                    {
                        sf = candidateSf;
                        cabReader = candidateReader;
                        break;
                    }
                }
                candidateReader.Dispose();
            }
            if (sf == null)
            {
                return null;
            }
            using var seedCabReader = cabReader;

            var targetInfo = sf.ObjectsByPathId[entry.PathID];
            cabReader.Position = 0;
            var objReader = new ObjectReader(cabReader, sf, targetInfo);
            var tree = TypeTreeHelper.ReadType(targetInfo.serializedType.m_Type, objReader);

            if (tree["lodSettings"] is not OrderedDictionary lodSettings ||
                lodSettings["_keyData"] is not List<object> lodKeys ||
                lodSettings["_valueData"] is not List<object> lodValues ||
                lodKeys.Count == 0)
            {
                return null;
            }

            var bestIdx = lodKeys.Select((k, idx) => (tier: Convert.ToInt32(k), idx)).OrderBy(x => x.tier).First().idx;
            if (lodValues[bestIdx] is not OrderedDictionary bestLod ||
                bestLod["m_rendererDataArr"] is not List<object> rendererArr ||
                rendererArr.Count == 0 ||
                rendererArr[0] is not OrderedDictionary rendererData)
            {
                return null;
            }

            var (meshFileId, meshPathId) = ReadPPtr((OrderedDictionary)rendererData["m_mesh"]);
            var mesh = ResolveMesh(sf, cabReader, meshFileId, meshPathId);
            if (mesh == null)
            {
                return null;
            }

            var pending = mesh.PendingStreamData;
            if (pending != null)
            {
                var bytes = _resolver.ResolveStreamedBytes(pending.path, pending.offset, pending.size);
                mesh.ResolveStreamedVertexData(bytes);
                mesh.ProcessData();
            }

            // Unity submeshes map 1:1 to material slots by index (m_materials[i] renders
            // m_SubMeshes[i]'s index range). A single mesh can carry several materials for
            // genuinely different surfaces - e.g. a storage tank's atlas-only fill-level shader
            // (submesh 0, no static texture) alongside its housing shell texture (submesh 1) and
            // liquid window (submesh 2). Reading only material/submesh 0 (the old assumption)
            // silently dropped whichever slot happened to sit later.
            var resolvedMaterials = new List<(int indexCount, byte[] baseColorPng, byte[] emissivePng, string materialName)>();
            if (rendererData["m_materials"] is List<object> materialRefs)
            {
                for (var slotIdx = 0; slotIdx < materialRefs.Count; slotIdx++)
                {
                    var slotIndexCount = slotIdx < mesh.m_SubMeshes.Count
                        ? (int)mesh.m_SubMeshes[slotIdx].indexCount
                        : 0;

                    if (materialRefs[slotIdx] is OrderedDictionary matRef)
                    {
                        var (matFileId, matPathId) = ReadPPtr(matRef);
                        var material = ResolveMaterial(sf, cabReader, matFileId, matPathId);
                        if (material != null)
                        {
                            var baseColorPng = ResolveTexturePng(material, "_BaseColorMap");
                            var emissivePng = ResolveTexturePng(material, "_EmissiveMap");
                            resolvedMaterials.Add((slotIndexCount, baseColorPng, emissivePng, material.Name));
                            continue;
                        }
                    }

                    resolvedMaterials.Add((slotIndexCount, null, null, "Material"));
                }
            }

            return GltfPart.FromMesh(mesh, resolvedMaterials);
        }

        private static (int fileId, long pathId) ReadPPtr(OrderedDictionary dict) =>
            (Convert.ToInt32(dict["m_FileID"]), Convert.ToInt64(dict["m_PathID"]));

        private Mesh ResolveMesh(SerializedFile sf, FileReader cabReader, int fileId, long pathId)
        {
            if (fileId == 0)
            {
                var localInfo = sf.ObjectsByPathId.GetValueOrDefault(pathId);
                if (localInfo == null) return null;
                cabReader.Position = 0;
                return new Mesh(new ObjectReader(cabReader, sf, localInfo));
            }

            var externalName = sf.m_Externals[fileId - 1].fileName;
            var (extSf, extReader) = _resolver.OpenCab(externalName);
            if (extSf == null || !extSf.ObjectsByPathId.TryGetValue(pathId, out var extInfo))
            {
                extReader?.Dispose();
                return null;
            }
            extReader.Position = 0;
            var mesh = new Mesh(new ObjectReader(extReader, extSf, extInfo));
            extReader.Dispose();
            return mesh;
        }

        private Material ResolveMaterial(SerializedFile sf, FileReader cabReader, int fileId, long pathId)
        {
            if (fileId == 0)
            {
                var localInfo = sf.ObjectsByPathId.GetValueOrDefault(pathId);
                if (localInfo == null) return null;
                cabReader.Position = 0;
                return new Material(new ObjectReader(cabReader, sf, localInfo));
            }

            var externalName = sf.m_Externals[fileId - 1].fileName;
            var (extSf, extReader) = _resolver.OpenCab(externalName);
            if (extSf == null || !extSf.ObjectsByPathId.TryGetValue(pathId, out var extInfo))
            {
                extReader?.Dispose();
                return null;
            }
            extReader.Position = 0;
            var mat = new Material(new ObjectReader(extReader, extSf, extInfo));
            extReader.Dispose();
            return mat;
        }

        private byte[] ResolveTexturePng(Material material, string propertyName)
        {
            var texEnvEntry = material.m_SavedProperties.m_TexEnvs.FirstOrDefault(t => t.Key == propertyName);
            if (texEnvEntry.Value?.m_Texture == null || texEnvEntry.Value.m_Texture.IsNull)
            {
                return null;
            }

            var texPPtr = texEnvEntry.Value.m_Texture;
            if (texPPtr.ExternalFileName == null)
            {
                return null;
            }

            var (texSf, texReader) = _resolver.OpenCab(texPPtr.ExternalFileName);
            if (texSf == null || !texSf.ObjectsByPathId.TryGetValue(texPPtr.m_PathID, out var texInfo))
            {
                texReader?.Dispose();
                return null;
            }

            texReader.Position = 0;
            var texture = new Texture2D(new ObjectReader(texReader, texSf, texInfo));

            byte[] rawBytes;
            if (texture.image_data.IsInline)
            {
                texReader.Position = texture.image_data.Offset;
                rawBytes = texReader.ReadBytes((int)texture.image_data.Size);
            }
            else
            {
                rawBytes = _resolver.ResolveStreamedBytes(texture.image_data.ExternalPath, texture.image_data.Offset, texture.image_data.Size);
            }
            texReader.Dispose();

            if (!TextureExporter.TryDecodeToRgba(texture, rawBytes, out var rgba))
            {
                return null;
            }

            using var pngStream = new MemoryStream();
            TextureExporter.WritePngToStream(rgba, texture.m_Width, texture.m_Height, pngStream);
            return pngStream.ToArray();
        }
    }
}
