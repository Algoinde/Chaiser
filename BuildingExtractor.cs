using System.Collections.Specialized;
using MessagePack;

namespace Chaiser
{
    /// <summary>
    /// Resolves a single FactoryUnitConfigAsset (by AssetMap name) all the way down to a real
    /// Mesh + decoded base color texture, following the exact chain validated interactively:
    /// AssetMap -> direct-offset VFS decompress -> type tree -> best LOD -> mesh/material PPtr
    /// resolution (same CAB or via CABMap for externals) -> streamed vertex/texture data.
    /// </summary>
    public class BuildingExtractor
    {
        private readonly AssetResolver _resolver;
        private readonly string _assetMapPath;
        private AssetMap _assetMap;

        public BuildingExtractor(string assetMapPath, string cabMapPath, string vfsRoot)
        {
            _assetMapPath = assetMapPath;
            _resolver = new AssetResolver(cabMapPath, vfsRoot);
        }

        private AssetMap LoadAssetMap()
        {
            if (_assetMap != null) return _assetMap;
            using var stream = File.OpenRead(_assetMapPath);
            _assetMap = MessagePackSerializer.Deserialize<AssetMap>(stream, MessagePackSerializerOptions.Standard.WithCompression(MessagePackCompression.Lz4BlockArray));
            return _assetMap;
        }

        public List<AssetEntry> ListBuildingEntries()
        {
            return LoadAssetMap().AssetEntries
                .Where(e => e.Type == ClassIDType.MonoBehaviour
                         && e.Container != null
                         && e.Container.Contains("ciautogenerated/pc/building/", StringComparison.OrdinalIgnoreCase))
                .ToList();
        }

        /// <summary>
        /// Resolves one FactoryUnitConfigAsset by exact AssetMap name to a GltfPart (mesh +
        /// decoded base color texture from its highest-detail LOD). Returns null if the name
        /// isn't found or has no usable renderer data - callers decide whether that's fatal.
        /// </summary>
        public GltfPart ResolvePart(string assetName)
        {
            // A name can also belong to an unrelated building MonoBehaviour (pump_2 has one under
            // gameplay/factory/building/), so the autogenerated unit config wins.
            var entry = LoadAssetMap().AssetEntries
                .Where(e => e.Name == assetName && e.Type == ClassIDType.MonoBehaviour)
                .OrderByDescending(e => e.Container?.Contains("ciautogenerated/pc/building/", StringComparison.OrdinalIgnoreCase) == true)
                .FirstOrDefault();
            if (entry == null)
            {
                return null;
            }

            using var seedReader = new FileReader(entry.Source);
            seedReader.Position = entry.Offset;
            var seedVfs = new VFSFile(seedReader, entry.Source);

            SerializedFile sf = null;
            FileReader cabReader = null;
            foreach (var node in seedVfs.Nodes)
            {
                var extracted = seedVfs.ExtractNode(node);
                var candidateReader = new FileReader(node.path, extracted, leaveOpen: true);
                if (candidateReader.FileType == FileType.AssetsFile)
                {
                    var candidateSf = new SerializedFile(candidateReader);
                    if (candidateSf.ObjectsByPathId.ContainsKey(entry.PathID))
                    {
                        sf = candidateSf;
                        cabReader = candidateReader;
                        break;
                    }
                }
                candidateReader.Dispose();
            }
            if (sf == null)
            {
                return null;
            }
            using var seedCabReader = cabReader;

            var targetInfo = sf.ObjectsByPathId[entry.PathID];
            cabReader.Position = 0;
            var objReader = new ObjectReader(cabReader, sf, targetInfo);
            var tree = TypeTreeHelper.ReadType(targetInfo.serializedType.m_Type, objReader);

            if (tree["lodSettings"] is not OrderedDictionary lodSettings ||
                lodSettings["_keyData"] is not List<object> lodKeys ||
                lodSettings["_valueData"] is not List<object> lodValues ||
                lodKeys.Count == 0)
            {
                return null;
            }

            var bestIdx = lodKeys.Select((k, idx) => (tier: Convert.ToInt32(k), idx)).OrderBy(x => x.tier).First().idx;
            if (lodValues[bestIdx] is not OrderedDictionary bestLod ||
                bestLod["m_rendererDataArr"] is not List<object> rendererArr ||
                rendererArr.Count == 0 ||
                rendererArr[0] is not OrderedDictionary rendererData)
            {
                return null;
            }

            var (meshFileId, meshPathId) = ReadPPtr((OrderedDictionary)rendererData["m_mesh"]);
            var mesh = ResolveMesh(sf, cabReader, meshFileId, meshPathId);
            if (mesh == null)
            {
                return null;
            }

            var pending = mesh.PendingStreamData;
            if (pending != null)
            {
                var bytes = _resolver.ResolveStreamedBytes(pending.path, pending.offset, pending.size);
                mesh.ResolveStreamedVertexData(bytes);
                mesh.ProcessData();
            }

            // Unity submeshes map 1:1 to material slots by index (m_materials[i] renders
            // m_SubMeshes[i]'s index range). A single mesh can carry several materials for
            // genuinely different surfaces - e.g. a storage tank's atlas-only fill-level shader
            // (submesh 0, no static texture) alongside its housing shell texture (submesh 1) and
            // liquid window (submesh 2). Reading only material/submesh 0 (the old assumption)
            // silently dropped whichever slot happened to sit later.
            var resolvedMaterials = new List<MaterialSlotData>();
            if (rendererData["m_materials"] is List<object> materialRefs)
            {
                for (var slotIdx = 0; slotIdx < materialRefs.Count; slotIdx++)
                {
                    var slotIndexCount = slotIdx < mesh.m_SubMeshes.Count
                        ? (int)mesh.m_SubMeshes[slotIdx].indexCount
                        : 0;

                    if (materialRefs[slotIdx] is OrderedDictionary matRef)
                    {
                        var (matFileId, matPathId) = ReadPPtr(matRef);
                        resolvedMaterials.Add(SlotOf(ResolveMaterial(sf, cabReader, matFileId, matPathId), slotIndexCount));
                        continue;
                    }

                    resolvedMaterials.Add(SlotOf(null, slotIndexCount));
                }
            }

            return GltfPart.FromMesh(mesh, resolvedMaterials);
        }

        /// <summary>
        /// Resolves a plain prefab (no FactoryUnitConfigAsset, e.g. the farm plots under
        /// gameplay/factory/soilmodel) by container path: its lod0 MeshFilter's mesh with the
        /// same GameObject's MeshRenderer materials. Null if the prefab has no such renderer.
        /// </summary>
        public GltfPart ResolvePrefabPart(string containerContains)
        {
            var entry = LoadAssetMap().AssetEntries.FirstOrDefault(e => e.Container != null
                && e.Container.Contains(containerContains, StringComparison.OrdinalIgnoreCase));
            if (entry == null) return null;

            using var seedReader = new FileReader(entry.Source);
            seedReader.Position = entry.Offset;
            var seedVfs = new VFSFile(seedReader, entry.Source);
            foreach (var node in seedVfs.Nodes)
            {
                var extracted = seedVfs.ExtractNode(node);
                using var reader = new FileReader(node.path, extracted, leaveOpen: true);
                if (reader.FileType != FileType.AssetsFile) continue;
                var sf = new SerializedFile(reader);
                if (!sf.ObjectsByPathId.ContainsKey(entry.PathID)) continue;

                OrderedDictionary Read(ObjectInfo info)
                {
                    reader.Position = 0;
                    return TypeTreeHelper.ReadType(info.serializedType.m_Type, new ObjectReader(reader, sf, info));
                }
                long GameObjectOf(OrderedDictionary tree) => ReadPPtr((OrderedDictionary)tree["m_GameObject"]).pathId;

                var names = sf.ObjectsByPathId.Values
                    .Where(i => (ClassIDType)i.classID == ClassIDType.GameObject)
                    .ToDictionary(i => i.m_PathID, i => Read(i)["m_Name"] as string ?? "");
                var filters = sf.ObjectsByPathId.Values
                    .Where(i => (ClassIDType)i.classID == ClassIDType.MeshFilter)
                    .Select(Read)
                    .ToList();
                var filter = filters.FirstOrDefault(f => names.GetValueOrDefault(GameObjectOf(f), "").EndsWith("_lod0", StringComparison.OrdinalIgnoreCase))
                             ?? filters.FirstOrDefault();
                if (filter == null) return null;
                var go = GameObjectOf(filter);
                var renderer = sf.ObjectsByPathId.Values
                    .Where(i => (ClassIDType)i.classID == ClassIDType.MeshRenderer)
                    .Select(Read)
                    .FirstOrDefault(r => GameObjectOf(r) == go);

                var (meshFileId, meshPathId) = ReadPPtr((OrderedDictionary)filter["m_Mesh"]);
                var mesh = ResolveMesh(sf, reader, meshFileId, meshPathId);
                if (mesh == null) return null;
                var pending = mesh.PendingStreamData;
                if (pending != null)
                {
                    mesh.ResolveStreamedVertexData(_resolver.ResolveStreamedBytes(pending.path, pending.offset, pending.size));
                    mesh.ProcessData();
                }

                var materials = new List<MaterialSlotData>();
                if (renderer?["m_Materials"] is List<object> refs)
                {
                    for (var slot = 0; slot < refs.Count; slot++)
                    {
                        var count = slot < mesh.m_SubMeshes.Count ? (int)mesh.m_SubMeshes[slot].indexCount : 0;
                        var (matFileId, matPathId) = ReadPPtr((OrderedDictionary)refs[slot]);
                        materials.Add(SlotOf(ResolveMaterial(sf, reader, matFileId, matPathId), count));
                    }
                }
                return GltfPart.FromMesh(mesh, materials);
            }
            return null;
        }

        private static (int fileId, long pathId) ReadPPtr(OrderedDictionary dict) =>
            (Convert.ToInt32(dict["m_FileID"]), Convert.ToInt64(dict["m_PathID"]));

        private Mesh ResolveMesh(SerializedFile sf, FileReader cabReader, int fileId, long pathId)
        {
            if (fileId == 0)
            {
                var localInfo = sf.ObjectsByPathId.GetValueOrDefault(pathId);
                if (localInfo == null) return null;
                cabReader.Position = 0;
                return new Mesh(new ObjectReader(cabReader, sf, localInfo));
            }

            var externalName = sf.m_Externals[fileId - 1].fileName;
            var (extSf, extReader) = _resolver.OpenCab(externalName);
            if (extSf == null || !extSf.ObjectsByPathId.TryGetValue(pathId, out var extInfo))
            {
                extReader?.Dispose();
                return null;
            }
            extReader.Position = 0;
            var mesh = new Mesh(new ObjectReader(extReader, extSf, extInfo));
            extReader.Dispose();
            return mesh;
        }

        private Material ResolveMaterial(SerializedFile sf, FileReader cabReader, int fileId, long pathId)
        {
            if (fileId == 0)
            {
                var localInfo = sf.ObjectsByPathId.GetValueOrDefault(pathId);
                if (localInfo == null) return null;
                cabReader.Position = 0;
                return new Material(new ObjectReader(cabReader, sf, localInfo));
            }

            var externalName = sf.m_Externals[fileId - 1].fileName;
            var (extSf, extReader) = _resolver.OpenCab(externalName);
            if (extSf == null || !extSf.ObjectsByPathId.TryGetValue(pathId, out var extInfo))
            {
                extReader?.Dispose();
                return null;
            }
            extReader.Position = 0;
            var mat = new Material(new ObjectReader(extReader, extSf, extInfo));
            extReader.Dispose();
            return mat;
        }

        public byte[] ResolveTexturePng(Material material, string propertyName)
        {
            if (ResolveTextureBgra(material, propertyName) is not var (bgra, width, height)) return null;
            using var pngStream = new MemoryStream();
            TextureExporter.WritePngToStream(bgra, width, height, pngStream);
            return pngStream.ToArray();
        }

        /// <summary>A texture slot decoded to BGRA, bottom row first (Unity's order).</summary>
        public (byte[] bgra, int width, int height)? ResolveTextureBgra(Material material, string propertyName)
        {
            var texEnvEntry = material.m_SavedProperties.m_TexEnvs.FirstOrDefault(t => t.Key == propertyName);
            if (texEnvEntry.Value?.m_Texture == null || texEnvEntry.Value.m_Texture.IsNull)
            {
                return null;
            }

            var texPPtr = texEnvEntry.Value.m_Texture;
            if (texPPtr.ExternalFileName == null)
            {
                return null;
            }

            var (texSf, texReader) = _resolver.OpenCab(texPPtr.ExternalFileName);
            if (texSf == null || !texSf.ObjectsByPathId.TryGetValue(texPPtr.m_PathID, out var texInfo))
            {
                texReader?.Dispose();
                return null;
            }

            texReader.Position = 0;
            var texture = new Texture2D(new ObjectReader(texReader, texSf, texInfo));

            byte[] rawBytes;
            if (texture.image_data.IsInline)
            {
                texReader.Position = texture.image_data.Offset;
                rawBytes = texReader.ReadBytes((int)texture.image_data.Size);
            }
            else
            {
                rawBytes = _resolver.ResolveStreamedBytes(texture.image_data.ExternalPath, texture.image_data.Offset, texture.image_data.Size);
            }
            texReader.Dispose();

            if (!TextureExporter.TryDecodeToRgba(texture, rawBytes, out var rgba))
            {
                return null;
            }
            return (rgba, texture.m_Width, texture.m_Height);
        }

        /// <summary>
        /// The surface maps in glTF's layout: a normal map (X, Y from the game's red and green,
        /// Z rebuilt) and one ORM texture (occlusion R, roughness G, metallic B). The game packs
        /// them two ways: _NormalMap as NRO (normal XY, roughness, occlusion) when there is no
        /// _MROMap, else _NormalMap holds only the normal and _MROMap metallic, roughness,
        /// occlusion. Nulls where the material has no normal map.
        /// </summary>
        public (byte[] normalPng, byte[] ormPng) ResolveSurfacePngs(Material material)
        {
            if (ResolveTextureBgra(material, "_NormalMap") is not var (nro, w, h)) return (null, null);
            var mro = ResolveTextureBgra(material, "_MROMap");
            if (mro is { } m && (m.width != w || m.height != h)) mro = null;

            var normal = new byte[nro.Length];
            var orm = new byte[nro.Length];
            for (var i = 0; i < nro.Length; i += 4)
            {
                // BGRA: [i] = B, [i + 1] = G, [i + 2] = R, [i + 3] = A.
                var x = nro[i + 2] / 127.5f - 1f;
                var y = nro[i + 1] / 127.5f - 1f;
                var z = MathF.Sqrt(MathF.Max(0f, 1f - x * x - y * y));
                normal[i] = (byte)MathF.Round((z + 1f) * 127.5f);
                normal[i + 1] = nro[i + 1];
                normal[i + 2] = nro[i + 2];
                normal[i + 3] = 255;

                byte occlusion, roughness, metallic;
                if (mro is { } packed)
                {
                    metallic = packed.bgra[i + 2];
                    roughness = packed.bgra[i + 1];
                    occlusion = packed.bgra[i];
                }
                else
                {
                    metallic = 0;
                    roughness = nro[i];
                    occlusion = nro[i + 3];
                }
                orm[i] = metallic;
                orm[i + 1] = roughness;
                orm[i + 2] = occlusion;
                orm[i + 3] = 255;
            }

            byte[] Png(byte[] bgra)
            {
                using var stream = new MemoryStream();
                TextureExporter.WritePngToStream(bgra, w, h, stream);
                return stream.ToArray();
            }
            return (Png(normal), Png(orm));
        }

        private MaterialSlotData SlotOf(Material material, int indexCount)
        {
            if (material == null) return new MaterialSlotData(indexCount, null, null, null, null, "Material");
            var (normalPng, ormPng) = ResolveSurfacePngs(material);
            return new MaterialSlotData(indexCount, ResolveTexturePng(material, "_BaseColorMap"),
                ResolveTexturePng(material, "_EmissiveMap"), normalPng, ormPng, material.Name);
        }
    }
}
